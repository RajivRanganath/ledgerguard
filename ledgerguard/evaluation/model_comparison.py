"""Run the same holdout through several investigator providers.

    python -m ledgerguard.evaluation.model_comparison --providers groq,gemini,stub

Everything except the investigator is held constant: same frozen holdout, same
deterministic engine, same Shadow Ledger, same Evidence Gate, same safety gate.
The only variable is which model proposes hypotheses.

The point is not to rank models. It is to show what the architecture does when
the investigator is good and when it is bad, on the same data -- and in
particular whether the Evidence Gate holds in both cases.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from ..ai.provider import get_provider
from ..ledger.money import to_rupees_str
from ..pipeline import run
from ..synthetic.fault_injector import build_dataset, split
from ..synthetic.generator import FaultClass
from .baseline import run_baseline
from .metrics import compute

OUTPUT_DIR = Path(__file__).parent / "outputs"


def summarise(metrics, report, dataset) -> dict:
    """Per-provider row, plus the two behaviours that matter on F3 and F6."""
    truth = {
        lc.payment.payment_id: dataset.ground_truth[lc.lifecycle_id]
        for lc in dataset.lifecycles
    }
    proposed_resolve_on_f6 = 0
    gate_rejected = 0
    gate_unverified = 0
    invalid_responses = 0
    unavailable = 0
    dropped_ids = 0

    for outcome in report.outcomes:
        inv = outcome.investigation
        if inv is None:
            continue
        result = inv.result
        if result.source == "invalid_response":
            invalid_responses += 1
        if result.source == "unavailable":
            unavailable += 1
        if result.error and "dropped ids" in (result.error or ""):
            dropped_ids += 1
        gt = truth[outcome.case.payment_id]
        if (
            gt.fault_class == FaultClass.F6_INCORRECT_LINKAGE
            and result.recommended_action == "resolve"
            and result.hypothesis != "insufficient_evidence"
        ):
            proposed_resolve_on_f6 += 1
        if outcome.verification:
            if outcome.verification.verdict == "REJECTED":
                gate_rejected += 1
            elif outcome.verification.verdict == "UNVERIFIED":
                gate_unverified += 1

    f6_total = sum(
        1
        for o in report.outcomes
        if truth[o.case.payment_id].fault_class == FaultClass.F6_INCORRECT_LINKAGE
    )
    f3 = metrics.per_fault_class.get(FaultClass.F3_UNLINKED_PARTIAL_REFUND, {})

    return {
        "provider": metrics.provider,
        "accuracy": metrics.accuracy,
        "auto_resolved": metrics.auto_resolved,
        "correctly_resolved": metrics.exceptions_correctly_resolved,
        "f3_resolved": f3.get("auto_resolved", 0),
        "f3_total": f3.get("n", 0),
        "f6_total": f6_total,
        "investigator_wanted_to_close_f6": proposed_resolve_on_f6,
        "gate_rejected": gate_rejected,
        "gate_unverified": gate_unverified,
        "false_auto_resolutions": metrics.false_auto_resolutions,
        "false_auto_resolved_value_inr": to_rupees_str(
            metrics.false_auto_resolved_value_paise
        ),
        "invalid_responses": invalid_responses,
        "unavailable": unavailable,
        "inadmissible_ids_dropped": dropped_ids,
        "latency_p50_ms": metrics.latency_p50_ms,
        "latency_p95_ms": metrics.latency_p95_ms,
        "wall_seconds": metrics.wall_seconds,
    }


def render(rows: list[dict], baseline_row: dict) -> str:
    all_rows = [baseline_row] + rows
    lines = [
        "# Investigator comparison",
        "",
        "Same frozen holdout, same deterministic engine, same Shadow Ledger, same",
        "Evidence Gate, same safety gate. The only variable is the investigator.",
        "",
        "Generated by `python -m ledgerguard.evaluation.model_comparison`.",
        "",
        "| Investigator | Accuracy | F3 resolved | Wanted to close an F6 | Gate rejected | Gate unverified | **False auto** | **Value falsely closed** |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in all_rows:
        lines.append(
            f"| `{r['provider']}` | {r['accuracy']:.1%} | {r['f3_resolved']}/{r['f3_total']} | "
            f"{r['investigator_wanted_to_close_f6']}/{r['f6_total']} | {r['gate_rejected']} | "
            f"{r['gate_unverified']} | **{r['false_auto_resolutions']}** | "
            f"**INR {r['false_auto_resolved_value_inr']}** |"
        )
    lines += [
        "",
        "## Reliability and latency",
        "",
        "| Investigator | Invalid responses | Unavailable | Inadmissible ids dropped | p50 ms | p95 ms | wall s |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in all_rows:
        lines.append(
            f"| `{r['provider']}` | {r['invalid_responses']} | {r['unavailable']} | "
            f"{r['inadmissible_ids_dropped']} | {r['latency_p50_ms']} | {r['latency_p95_ms']} | "
            f"{r['wall_seconds']} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compare investigator providers")
    parser.add_argument("--providers", default="groq,gemini,stub")
    parser.add_argument("--seed", type=int, default=20260905)
    parser.add_argument("--count", type=int, default=320)
    args = parser.parse_args(argv)

    full = build_dataset(seed=args.seed, count=args.count)
    _dev, holdout = split(full)
    lbp = holdout.lifecycle_by_payment()
    batch = holdout.batch()

    base_report = run_baseline(batch, lbp)
    base_row = summarise(compute(base_report, holdout), base_report, holdout)
    base_row["provider"] = "rules only (no investigator)"

    rows = []
    for name in [p.strip() for p in args.providers.split(",") if p.strip()]:
        print(f"running {name} ...", flush=True)
        provider = get_provider(name)
        report = run(batch, use_ai=True, provider=provider, lifecycle_by_payment=lbp)
        rows.append(summarise(compute(report, holdout), report, holdout))
        print(f"  done: {rows[-1]['provider']}", flush=True)

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    md = render(rows, base_row)
    (OUTPUT_DIR / "model_comparison.md").write_text(md)
    (OUTPUT_DIR / "model_comparison.json").write_text(
        json.dumps({"baseline": base_row, "providers": rows}, indent=2) + "\n"
    )
    print("\n" + md)
    print(f"Artifacts written to {OUTPUT_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
