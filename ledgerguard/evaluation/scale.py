"""Scale check: does the deterministic core hold at 10,000+ lifecycles?

The headline dataset is 320 lifecycles because known ground truth against
controlled faults is what makes the results mean anything -- not volume. But
"we kept it small on purpose" is only credible if the thing actually runs large,
so this measures the deterministic path at 10k+ and confirms the properties that
must not degrade with size:

  * no clean lifecycle is falsely flagged, at any scale
  * no injected fault is missed, at any scale
  * throughput stays linear rather than quadratic

The AI layer is not exercised here. It is bounded by rate limits, not by data
size, and its cost is reported per 100 records in the benchmark instead.

    python -m ledgerguard.evaluation.scale
"""

from __future__ import annotations

import argparse
import json
import time
from dataclasses import asdict, dataclass
from pathlib import Path

from ..pipeline import run
from ..reconciliation.matcher import MATCHED
from ..synthetic.fault_injector import build_dataset
from ..synthetic.generator import FaultClass

OUTPUT_DIR = Path(__file__).parent / "outputs"


@dataclass
class ScalePoint:
    lifecycles: int
    records: int
    generate_seconds: float
    reconcile_seconds: float
    throughput_per_second: float
    microseconds_per_case: float
    matched: int
    exceptions: int
    false_exceptions: int
    missed_faults: int
    fault_classes_present: int


def measure(count: int, seed: int = 20260905) -> ScalePoint:
    t0 = time.perf_counter()
    dataset = build_dataset(seed=seed, count=count)
    generate_seconds = time.perf_counter() - t0

    batch = dataset.batch()
    records = (
        len(batch.orders) + len(batch.payments) + len(batch.refunds)
        + len(batch.settlements) + len(batch.bank_entries)
    )
    fault = dataset.fault_class_by_payment()

    t0 = time.perf_counter()
    report = run(batch, use_ai=False, lifecycle_by_payment=dataset.lifecycle_by_payment())
    reconcile_seconds = time.perf_counter() - t0

    matched = false_exceptions = missed = 0
    for outcome in report.outcomes:
        clean = fault[outcome.case.payment_id] == FaultClass.NONE
        if outcome.state == MATCHED:
            matched += 1
            if not clean:
                missed += 1
        elif clean:
            false_exceptions += 1

    total = len(report.outcomes)
    return ScalePoint(
        lifecycles=count,
        records=records,
        generate_seconds=round(generate_seconds, 3),
        reconcile_seconds=round(reconcile_seconds, 3),
        throughput_per_second=round(total / reconcile_seconds, 1) if reconcile_seconds else 0.0,
        microseconds_per_case=round(1e6 * reconcile_seconds / total, 1) if total else 0.0,
        matched=matched,
        exceptions=total - matched,
        false_exceptions=false_exceptions,
        missed_faults=missed,
        fault_classes_present=len(set(fault.values()) - {FaultClass.NONE}),
    )


def render(points: list[ScalePoint]) -> str:
    lines = [
        "# Scale check (deterministic path)",
        "",
        "Generated by `python -m ledgerguard.evaluation.scale`.",
        "",
        "| Lifecycles | Records | Generate (s) | Reconcile (s) | Cases/s | µs/case | False exceptions | Missed faults |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for p in points:
        lines.append(
            f"| {p.lifecycles:,} | {p.records:,} | {p.generate_seconds} | "
            f"{p.reconcile_seconds} | {p.throughput_per_second:,} | "
            f"{p.microseconds_per_case} | **{p.false_exceptions}** | **{p.missed_faults}** |"
        )
    biggest = points[-1]
    first, last = points[0], points[-1]
    growth = (
        (last.microseconds_per_case / first.microseconds_per_case)
        if first.microseconds_per_case else 0.0
    )
    lines += [
        "",
        f"At {biggest.lifecycles:,} lifecycles ({biggest.records:,} records) the deterministic "
        f"path reconciles in {biggest.reconcile_seconds}s with {biggest.false_exceptions} false "
        f"exceptions and {biggest.missed_faults} missed faults.",
        "",
        f"Per-case cost changed by {growth:.2f}x across a "
        f"{last.lifecycles // first.lifecycles}x increase in size — "
        + ("linear, as intended." if growth < 3 else "**worse than linear; investigate.**"),
        "",
        "The dataset stays at 320 for every published result. Volume is not what",
        "makes the evaluation meaningful; known ground truth against controlled",
        "faults is. This page exists to show that the choice was a choice.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Scale check")
    parser.add_argument("--sizes", default="320,1000,5000,12000")
    args = parser.parse_args(argv)

    points = []
    for size in [int(s) for s in args.sizes.split(",")]:
        print(f"measuring {size} lifecycles ...", flush=True)
        point = measure(size)
        assert point.false_exceptions == 0, f"false exceptions at {size}"
        assert point.missed_faults == 0, f"missed faults at {size}"
        assert point.fault_classes_present == 6, f"lost a fault class at {size}"
        points.append(point)

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    md = render(points)
    (OUTPUT_DIR / "scale.md").write_text(md)
    (OUTPUT_DIR / "scale.json").write_text(
        json.dumps([asdict(p) for p in points], indent=2) + "\n"
    )
    print("\n" + md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
